#!/usr/bin/env python3
"""Twenty actual label writers in an explicitly enabled disposable fixture only."""
import json
import os
import sys
from check_workspace_concurrency import Probe, CheckFailure, outcome


def permitted(environment):
    local = environment.get('PGHOST') in ('127.0.0.1', '::1')
    ci = environment.get('PGHOST') == 'postgres' and environment.get('GITHUB_ACTIONS') == 'true'
    return (environment.get('JOBMATCH_LOCAL_SPECIALTY_TEST') == '1' and (local or ci)
            and environment.get('PGDATABASE') == 'structured_upgrade'
            and not any(environment.get(key) for key in ('PGSERVICE', 'PGHOSTADDR', 'PGSERVICEFILE')))


class SpecialtyProbe(Probe):
    def __init__(self, environment):
        super().__init__(environment)
        self.owns_fixtures = False

    def run(self):
        self.stage = 'specialty setup'
        self.query("BEGIN; INSERT INTO auth.users(id) VALUES ('%s'),('%s'); "
                   "INSERT INTO auth.sessions(id,user_id) VALUES ('%s','%s'),('%s','%s'); COMMIT;"
                   % (self.a, self.b, self.sa, self.a, self.sb, self.b))
        self.owns_fixtures = True
        claims = json.dumps({'sub': self.a, 'session_id': self.sa})
        self.query("BEGIN; SET LOCAL request.jwt.claims='%s'; SET LOCAL ROLE authenticated; "
                   "DO $$BEGIN PERFORM public.apply_workspace_command(0,"
                   "'{\"action\":\"application\",\"title\":\"SYNTHETIC race\",\"status\":\"Планируется\",\"note\":\"keep\"}'); END;$$; COMMIT;" % claims)
        app_id = self.query("SELECT id FROM public.applications WHERE user_id='%s';" % self.a).strip()
        # The identifier is generated by PostgreSQL, but still validate before SQL construction.
        import uuid
        if str(uuid.UUID(app_id)) != app_id:
            raise CheckFailure('Unexpected synthetic identifier')
        self.stage = 'specialty writer race'
        holder = self.owner_lock()
        names = ['jobmatch_specialty_%02d' % i for i in range(20)]
        workers = []
        for i, name in enumerate(names):
            command = json.dumps({'action': 'application', 'id': app_id, 'status': 'Планируется',
                                  'note': 'keep', 'specialty': 'SYNTHETIC label %02d' % i}, ensure_ascii=False)
            sql = """BEGIN;
CREATE FUNCTION pg_temp.attempt_specialty() RETURNS text LANGUAGE plpgsql AS $probe$
BEGIN PERFORM public.apply_workspace_command(1,'%s'); RETURN 'OK';
EXCEPTION WHEN raise_exception THEN
 IF SQLERRM='CONFLICT' THEN RETURN 'CONFLICT'; END IF; RAISE;
END;$probe$;
SET LOCAL request.jwt.claims='%s'; SET LOCAL ROLE authenticated;
SELECT pg_temp.attempt_specialty(); COMMIT;
""" % (command, claims)
            workers.append(self.child(sql, name))
        self.wait_for(names, 'advisory')
        self.finish(holder, 'COMMIT;\n')
        results = [outcome(self.finish(worker)) for worker in workers]
        if results.count('OK') != 1 or results.count('CONFLICT') != 19:
            raise CheckFailure('Specialty race did not have one winner')
        self.query("""DO $$BEGIN
 IF (SELECT revision FROM public.workspaces WHERE user_id='%s')<>2
  OR (SELECT count(*) FROM public.audit_log WHERE user_id='%s')<>2
  OR (SELECT count(*) FROM public.application_events WHERE user_id='%s')<>1
  OR (SELECT count(*) FROM public.applications WHERE user_id='%s')<>1
  OR NOT EXISTS(SELECT 1 FROM public.applications WHERE user_id='%s' AND id='%s'
      AND title='SYNTHETIC race' AND status='Планируется' AND note='keep'
      AND extra->>'specialty' ~ '^SYNTHETIC label [0-1][0-9]$')
  OR (private.workspace_projection_report()->'ok') IS DISTINCT FROM 'true'::jsonb
 THEN RAISE EXCEPTION 'QA_SPECIALTY_STATE';END IF;
END;$$;""" % (self.a, self.a, self.a, self.a, self.a, app_id))

    def cleanup(self):
        if self.owns_fixtures:
            super().cleanup()
        elif self.children:
            raise CheckFailure('Unowned fixture cleanup refused')


def main():
    if not permitted(os.environ):
        print('REFUSED: explicit disposable specialty fixture required.', file=sys.stderr)
        return 2
    probe = SpecialtyProbe(os.environ)
    success = False
    try:
        probe.run()
        success = True
    except Exception:
        print('FAIL: synthetic specialty concurrency; no row data or database diagnostics emitted.', file=sys.stderr)
    finally:
        try:
            probe.cleanup()
        except Exception:
            success = False
            print('FAIL: synthetic specialty cleanup.', file=sys.stderr)
    if success:
        print('PASS: twenty actual specialty writers; one commit, nineteen conflicts; lifecycle unchanged; fixtures removed.')
    return 0 if success else 1


if __name__ == '__main__':
    raise SystemExit(main())
